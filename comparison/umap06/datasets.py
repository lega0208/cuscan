"""Deterministic, hash-verified on-disk Phase 0 datasets.

The evaluation cache is deliberately not generated by this module.
"""

import hashlib
import json
import os
import tempfile
from pathlib import Path

import numpy as np
from sklearn.datasets import load_digits

from .spec import FIXTURES

SEED = 20261014
_CHUNK_ROWS = 1_000_000
_SCHEMA = "cuscan-umap06-fixtures-v1"


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        while chunk := stream.read(1024 * 1024):
            digest.update(chunk)
    return digest.hexdigest()


def _read_manifest(root: Path) -> dict:
    with (root / "manifest.json").open(encoding="utf-8") as stream:
        manifest = json.load(stream)
    if manifest.get("schema") != _SCHEMA or not isinstance(manifest.get("fixtures"), dict):
        raise ValueError("invalid fixture manifest")
    return manifest


def _expected_files(name: str) -> dict[str, tuple[list[int], str]]:
    fixture = FIXTURES[name]
    files = {"train.f32": ([fixture.rows, fixture.features], "<f4")}
    files.update({f"heldout_{n}.f32": ([n, fixture.features], "<f4") for n in fixture.batches})
    if name in ("blobs_1k", "digits") or name.startswith("mix_"):
        files["labels.i32"] = ([fixture.rows], "<i4")
    return files


def _verify_fixture(root: Path, name: str, record: dict) -> None:
    expected = _expected_files(name)
    if not isinstance(record, dict) or not isinstance(record.get("files"), dict):
        raise ValueError(f"invalid manifest record for {name}")
    if set(record["files"]) != set(expected):
        raise ValueError(f"unexpected file list for {name}")
    if not isinstance(record.get("seed"), int) or not isinstance(record.get("source_sha256"), str):
        raise ValueError(f"invalid provenance for {name}")
    for filename, (shape, dtype) in expected.items():
        info = record["files"][filename]
        if not isinstance(info, dict) or info.get("shape") != shape or info.get("dtype") != dtype:
            raise ValueError(f"invalid metadata for {name}/{filename}")
        path = root / name / filename
        if path.stat().st_size != int(np.prod(shape)) * np.dtype(dtype).itemsize:
            raise ValueError(f"incorrect size for {name}/{filename}")
        if _sha256(path) != info.get("sha256"):
            raise ValueError(f"hash mismatch for {name}/{filename}")


def verify(root: Path) -> list[str]:
    """Return human-readable integrity errors; an empty list means verified."""
    root = Path(root)
    try:
        manifest = _read_manifest(root)
    except (OSError, ValueError, TypeError) as exc:
        return [f"manifest: {exc}"]
    errors = []
    for name, record in manifest["fixtures"].items():
        if name not in FIXTURES:
            errors.append(f"unknown fixture: {name}")
            continue
        try:
            _verify_fixture(root, name, record)
        except (OSError, ValueError, TypeError, KeyError) as exc:
            errors.append(f"{name}: {exc}")
    return errors


def fixture_hash(root: Path, name: str) -> str:
    """Hash the canonical verified manifest record, including all fixture files."""
    root = Path(root)
    record = _read_manifest(root)["fixtures"][name]
    _verify_fixture(root, name, record)
    encoded = json.dumps(record, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(encoded).hexdigest()


def load_fixture(
    root: Path, name: str
) -> tuple[np.ndarray, dict[int, np.ndarray], np.ndarray | None]:
    """Verify all files before returning memory-mapped training and held-out arrays."""
    root = Path(root)
    fixture = FIXTURES[name]
    record = _read_manifest(root)["fixtures"][name]
    _verify_fixture(root, name, record)
    directory = root / name
    train = np.memmap(
        directory / "train.f32", dtype="<f4", mode="r", shape=(fixture.rows, fixture.features)
    )
    heldout = {
        n: np.memmap(
            directory / f"heldout_{n}.f32", dtype="<f4", mode="r", shape=(n, fixture.features)
        )
        for n in fixture.batches
    }
    labels_path = directory / "labels.i32"
    labels = (
        np.memmap(labels_path, dtype="<i4", mode="r", shape=(fixture.rows,))
        if "labels.i32" in record["files"]
        else None
    )
    return (
        np.asarray(train),
        {count: np.asarray(values) for count, values in heldout.items()},
        None if labels is None else np.asarray(labels),
    )


def _generate_fixture(directory: Path, name: str) -> dict:
    fixture = FIXTURES[name]
    rng = np.random.default_rng(SEED)
    labels = None
    if name == "digits":
        digits = load_digits()
        order = rng.permutation(len(digits.data))
        train = np.asarray(digits.data[order[: fixture.rows]], dtype="<f4", order="C")
        train.tofile(directory / "train.f32")
        labels = np.asarray(digits.target[order[: fixture.rows]], dtype="<i4")
        for n in fixture.batches:
            np.asarray(
                digits.data[order[fixture.rows : fixture.rows + n]], dtype="<f4", order="C"
            ).tofile(directory / f"heldout_{n}.f32")
    else:
        if name == "curve_20k":
            projection = np.linalg.qr(rng.normal(size=(fixture.features, 3)))[0].T
        elif name == "blobs_1k":
            centers = rng.normal(0, 1, size=(10, fixture.features))
            scales = rng.uniform(0.2, 1.5, size=(10, fixture.features))
        else:
            supercenters = rng.normal(0, 1, size=(5, fixture.features))
            centers = (
                supercenters[:, None, :] + rng.normal(0, 0.35, size=(5, 4, fixture.features))
            ).reshape(20, fixture.features)
        label_path = directory / "labels.i32"
        label_stream = label_path.open("wb") if name != "curve_20k" else None
        try:
            for filename, count, training in [
                ("train.f32", fixture.rows, True),
                *[(f"heldout_{n}.f32", n, False) for n in fixture.batches],
            ]:
                with (directory / filename).open("wb") as stream:
                    for start in range(0, count, _CHUNK_ROWS):
                        n = min(_CHUNK_ROWS, count - start)
                        if name == "curve_20k":
                            t = rng.uniform(1.5 * np.pi, 4.5 * np.pi, size=n)
                            height = rng.uniform(0, 21, size=n)
                            points = np.column_stack((t * np.cos(t), height, t * np.sin(t)))
                            data = points @ projection + rng.normal(
                                0, 0.2, size=(n, fixture.features)
                            )
                        else:
                            ids = rng.integers(0, len(centers), size=n)
                            noise = rng.normal(size=(n, fixture.features))
                            data = centers[ids] + noise * (
                                scales[ids] if name == "blobs_1k" else 0.2
                            )
                            if training and label_stream is not None:
                                np.asarray(ids, dtype="<i4").tofile(label_stream)
                        np.asarray(data, dtype="<f4", order="C").tofile(stream)
        finally:
            if label_stream is not None:
                label_stream.close()
    if labels is not None:
        labels.tofile(directory / "labels.i32")
    files = {}
    for filename, (shape, dtype) in _expected_files(name).items():
        files[filename] = {"sha256": _sha256(directory / filename), "shape": shape, "dtype": dtype}
    return {"seed": SEED, "source_sha256": _sha256(Path(__file__)), "files": files}


def generate(root: Path, fixture_names: list[str] | None = None) -> dict:
    """Generate missing fixtures; never replace an unverified or untracked file."""
    root = Path(root)
    names = list(FIXTURES) if fixture_names is None else list(fixture_names)
    if len(set(names)) != len(names) or any(name not in FIXTURES for name in names):
        raise ValueError("duplicate or unknown fixture name")
    root.mkdir(parents=True, exist_ok=True)
    manifest_path = root / "manifest.json"
    manifest: dict
    if manifest_path.exists():
        manifest = _read_manifest(root)
        errors = verify(root)
        if errors:
            raise ValueError("fixture verification failed: " + "; ".join(errors))
    else:
        manifest = {"schema": _SCHEMA, "fixtures": {}}
    for name in names:
        if name in manifest["fixtures"]:
            continue
        destination = root / name
        if destination.exists():
            raise FileExistsError(f"untracked fixture directory: {destination}")
        with tempfile.TemporaryDirectory(prefix=f".{name}-", dir=root) as temp:
            record = _generate_fixture(Path(temp), name)
            # rename refuses a non-empty destination, but explicitly check empty directories too.
            if destination.exists():
                raise FileExistsError(f"fixture directory appeared: {destination}")
            os.rename(temp, destination)
        manifest["fixtures"][name] = record
        with tempfile.NamedTemporaryFile(
            mode="w", encoding="utf-8", dir=root, prefix=".manifest-", delete=False
        ) as stream:
            temporary = Path(stream.name)
            try:
                json.dump(manifest, stream, indent=2, sort_keys=True)
                stream.write("\n")
            except BaseException:
                temporary.unlink(missing_ok=True)
                raise
        try:
            os.replace(temporary, manifest_path)
        finally:
            temporary.unlink(missing_ok=True)
    return manifest
