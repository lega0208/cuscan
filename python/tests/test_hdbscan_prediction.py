import warnings
from pathlib import Path
from typing import Any, Literal

import hdbscan
import hdbscan.prediction as hp
import numpy as np
import pytest
from hdbscan.plots import CondensedTree

from fast_umap import HDBSCAN, HDBSCANPredictor, _fast_umap

FIXTURE_DIR = Path(__file__).parents[2] / "crates/fast-hdbscan/tests/fixtures"
FIXTURE_PATH = FIXTURE_DIR / "hdbscan_prediction.json"
GENERATOR_PATH = FIXTURE_DIR / "generate_hdbscan_prediction.py"
FIXTURE = json.loads(FIXTURE_PATH.read_text())
FITTED = {case["id"]: case for case in FIXTURE["fitted"]}
CLUSTERED_CASES = [case_id for case_id, case in FITTED.items() if not case["no_cluster_tree"]]
SHORTCUT_CASES = [case_id for case_id, case in FITTED.items() if case["no_cluster_tree"]]
RTOL = 1e-5
ATOL = 1e-6
F64_MAX = np.finfo(np.float64).max
RAW_TREE_DTYPE = np.dtype(
    [("parent", np.intp), ("child", np.intp), ("lambda_val", np.float64), ("child_size", np.intp)]
)
NO_CLUSTER_WARNING = "does not have any defined clusters"

Backend = Literal["cpu", "cuda"]


# ---------------------------------------------------------------------------
# Helpers


def floats(values: Any) -> np.ndarray:
    return np.asarray([float(v) for v in values], dtype=np.float64)


def matrix(rows: Any) -> np.ndarray:
    return np.asarray([[float(v) for v in row] for row in rows], dtype=np.float64)


def case_arrays(case_id: str) -> tuple[np.ndarray, np.ndarray]:
    case = FITTED[case_id]
    train = matrix(case["train_float32"]).astype(np.float32)
    queries = matrix(case["queries_float32"]).astype(np.float32)
    return train, queries


def order_sensitive_queries(case: dict[str, Any]) -> set[int]:
    return {
        note["query"]
        for note in case.get("tie_annotations", [])
        if note["connector_order_sensitive"]
    }


def fit_model(backend: Backend, case_id: str, **overrides: Any) -> HDBSCAN:
    params = {**FITTED[case_id]["params"], **overrides}
    train, _ = case_arrays(case_id)
    return HDBSCAN(backend=backend, **params).fit(train)


def predict(model: HDBSCAN, x: Any, connectors: bool | np.bool_ = True) -> tuple[np.ndarray, ...]:
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", UserWarning)
        return model.approximate_predict(x, return_connecting_points=connectors)


def same_hierarchy_oracle(
    model: HDBSCAN, train_raw: np.ndarray, queries: np.ndarray, min_samples: int
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """Original prediction over this model's fitted tree and float32 geometry.

    Returns labels, strengths, raw-row connectors, and prediction cores.
    Point children are translated from raw row IDs to compact finite IDs for
    the reference and connectors are translated back.
    """
    finite_index = np.asarray(model.finite_index_, dtype=np.intp)
    n_raw = train_raw.shape[0]
    raw_to_compact = np.full(n_raw, -1, dtype=np.intp)
    raw_to_compact[finite_index] = np.arange(finite_index.size)
    public = model.condensed_tree_
    # The public tree also attaches nonfinite raw rows; drop those point rows.
    public_children = np.asarray(public["child"], dtype=np.intp)
    is_point = public["child_size"] == 1
    keep = ~is_point | (
        (public_children < n_raw) & (raw_to_compact[np.minimum(public_children, n_raw - 1)] >= 0)
    )
    public = public[keep]
    tree = np.empty(public.shape[0], dtype=RAW_TREE_DTYPE)
    tree["parent"] = public["parent"]
    tree["lambda_val"] = public["lambda_val"]
    tree["child_size"] = public["child_size"].astype(np.intp)
    children = np.asarray(public["child"], dtype=np.intp)
    points = tree["child_size"] == 1
    assert np.all(children[points] < n_raw)
    compact_children = children.copy()
    compact_children[points] = raw_to_compact[children[points]]
    assert np.all(compact_children[points] >= 0), "tree attaches a nonfinite row"
    tree["child"] = compact_children
    labels = np.asarray(model.labels_, dtype=np.intp)[finite_index]
    compact = train_raw[finite_index].astype(np.float32).astype(np.float64)
    condensed = CondensedTree(tree, labels)
    prediction_data = hp.PredictionData(compact, condensed, min_samples, tree_type="kdtree")
    adapter = types.SimpleNamespace(
        prediction_data_=prediction_data,
        condensed_tree_=condensed,
        min_samples=min_samples,
        min_cluster_size=min_samples,
    )
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        out_labels, strengths, connectors = hp.approximate_predict(
            adapter, queries.astype(np.float64), return_connecting_points=True
        )
    connectors = np.asarray(connectors, dtype=np.intp)
    raw = np.where(connectors >= 0, finite_index[np.maximum(connectors, 0)], -1)
    return (
        np.asarray(out_labels, dtype=np.intp),
        np.asarray(strengths, dtype=np.float64),
        raw,
        np.asarray(prediction_data.core_distances, dtype=np.float64),
    )


def label_alignment(ours: np.ndarray, reference: np.ndarray) -> dict[int, int]:
    """Reference label -> our label, requiring identical training partitions."""
    np.testing.assert_array_equal(
        ours < 0, reference < 0, err_msg="training noise masks differ (fit, not prediction)"
    )
    mapping: dict[int, int] = {}
    for ref_label in np.unique(reference[reference >= 0]):
        our_labels = np.unique(ours[reference == ref_label])
        assert our_labels.size == 1, "training partitions differ (fit, not prediction)"
        mapping[int(ref_label)] = int(our_labels[0])
    assert len(set(mapping.values())) == len(mapping)
    return mapping


