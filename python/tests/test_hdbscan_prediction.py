@pytest.mark.parametrize("case_id", CLUSTERED_CASES)
def test_same_hierarchy_matches_original_prediction(case_id: str, hdbscan_backend: Backend) -> None:
    case = FITTED[case_id]
    train, queries = case_arrays(case_id)
    model = fit_model(hdbscan_backend, case_id)
    s = case["resolved_min_samples"]
    exp_labels, exp_strengths, exp_connectors, _ = same_hierarchy_oracle(
        model, train.astype(np.float64), queries, s
    )
    labels, strengths, connectors = predict(model, queries)
    stable = np.array(
        [i not in order_sensitive_queries(case) for i in range(len(queries))], dtype=bool
    )
    # Tie annotations exempt only connector identity; labels and strengths stay fully gated.
    np.testing.assert_array_equal(labels, exp_labels)
    np.testing.assert_array_equal(connectors[stable], exp_connectors[stable])
    np.testing.assert_allclose(strengths, exp_strengths, rtol=RTOL, atol=ATOL)
    assert np.all((strengths >= 0) & (strengths <= 1))
    np.testing.assert_array_equal(strengths[labels < 0], 0.0)


@pytest.mark.parametrize("case_id", CLUSTERED_CASES)
def test_training_coordinate_queries_match_same_hierarchy(
    case_id: str, hdbscan_backend: Backend
) -> None:
    case = FITTED[case_id]
    train, _ = case_arrays(case_id)
    model = fit_model(hdbscan_backend, case_id)
    finite = train[np.isfinite(train).all(axis=1)]
    queries = finite[:: max(1, finite.shape[0] // 12)]
    exp_labels, exp_strengths, _, _ = same_hierarchy_oracle(
        model, train.astype(np.float64), queries, case["resolved_min_samples"]
    )
    labels, strengths = predict(model, queries, connectors=False)
    np.testing.assert_array_equal(labels < 0, exp_labels < 0)
    np.testing.assert_allclose(strengths, exp_strengths, rtol=RTOL, atol=ATOL)


