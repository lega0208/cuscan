@pytest.mark.parametrize("record", FIXTURE["width"], ids=lambda r: f"s{r['min_samples']}")
def test_prediction_width_contract(record: dict[str, Any], hdbscan_backend: Backend) -> None:
    train = np.array([[0.0], [0.1], [0.25], [0.4], [5.0], [5.12], [5.3], [5.41]], np.float32)
    s = record["min_samples"]
    try:
        model = HDBSCAN(
            backend=hdbscan_backend, min_cluster_size=record["min_cluster_size"], min_samples=s
        ).fit(train)
    except ValueError:
        assert s > record["n_finite"], "fit may reject only min_samples beyond the row count"
        return
    if model.condensed_tree_[model.condensed_tree_["child_size"] > 1].size == 0:
        predict(model, train[:1])
        return
    query = np.array([[0.2]], np.float32)
    if record["project_outcome"] == "ok":
        labels, strengths = predict(model, query, connectors=False)
        assert labels.shape == strengths.shape == (1,)
    else:
        with pytest.raises(ValueError):
            model.approximate_predict(query)


