# Layer 3: independent original fit.


@pytest.mark.parametrize("case_id", CLUSTERED_CASES)
def test_independent_original_fit_parity(case_id: str, hdbscan_backend: Backend) -> None:
    case = FITTED[case_id]
    _, queries = case_arrays(case_id)
    model = fit_model(hdbscan_backend, case_id)
    finite_index = np.asarray(case["finite_index"], dtype=np.intp)
    np.testing.assert_array_equal(model.finite_index_, finite_index)
    mapping = label_alignment(
        np.asarray(model.labels_)[finite_index], np.asarray(case["labels_compact"])
    )
    expected = case["expected"]
    exp_labels = np.array(
        [mapping[label] if label >= 0 else -1 for label in expected["labels"]], dtype=np.intp
    )
    labels, strengths, connectors = predict(model, queries)
    np.testing.assert_array_equal(labels, exp_labels)
    np.testing.assert_allclose(strengths, floats(expected["strengths"]), rtol=RTOL, atol=ATOL)
    stable = [i for i in range(len(queries)) if i not in order_sensitive_queries(case)]
    np.testing.assert_array_equal(
        connectors[stable], np.asarray(expected["connecting_points_raw"])[stable]
    )


