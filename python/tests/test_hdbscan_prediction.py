@pytest.mark.parametrize("case_id", SHORTCUT_CASES)
def test_no_cluster_tree_shortcut_warns_once(case_id: str, hdbscan_backend: Backend) -> None:
    _, queries = case_arrays(case_id)
    model = fit_model(hdbscan_backend, case_id)
    for flag in (False, True):
        with warnings.catch_warnings(record=True) as caught:
            warnings.simplefilter("always")
            result = model.approximate_predict(queries, return_connecting_points=flag)
        relevant = [w for w in caught if NO_CLUSTER_WARNING in str(w.message)]
        assert len(relevant) == 1
        assert relevant[0].filename == __file__
        assert len(result) == (3 if flag else 2)
        np.testing.assert_array_equal(result[0], -1)
        assert result[1].dtype == np.float64
        np.testing.assert_array_equal(result[1], 0.0)
        if flag:
            assert len(result) == 3
            np.testing.assert_array_equal(result[2], -1)


