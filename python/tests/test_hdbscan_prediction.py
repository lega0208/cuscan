def test_mixed_nonfinite_training_connectors_use_raw_rows(hdbscan_backend: Backend) -> None:
    case = FITTED["mixed_nonfinite_training"]
    train, queries = case_arrays("mixed_nonfinite_training")
    model = fit_model(hdbscan_backend, "mixed_nonfinite_training")
    _, _, connectors = predict(model, queries)
    finite_rows = np.isfinite(train).all(axis=1)
    assert np.all(finite_rows[connectors])
    np.testing.assert_array_equal(connectors, case["expected"]["connecting_points_raw"])
