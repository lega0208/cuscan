"""Acceptance tests for fitted ``HDBSCAN.approximate_predict``.

Reference semantics come from the original ``hdbscan`` package (a development
oracle only; deliberately not ``importorskip``-ed). Fixtures are generated by
``crates/fast-hdbscan/tests/fixtures/generate_hdbscan_prediction.py``.

Comparison layers are kept separate (see approx_predict_plan.md section 9):

1. Fixed candidates/hierarchies: pinned in the fixture and checked against the
   original helpers by regeneration.
2. Same fitted hierarchy: original ``PredictionData`` built from *this* model's
   tree, labels and float32 geometry.
3. Independent original fit: training partitions must agree first; predicted
   labels are aligned through training memberships.
"""

from __future__ import annotations

import importlib.util
